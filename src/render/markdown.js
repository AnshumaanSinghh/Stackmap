// STACK.md: a readable inventory of the system, with a link to the code behind every claim.
// Good for onboarding docs, design reviews, and as context for AI coding agents.

import { blobUrl, shortSha } from '../git.js';
import { CATEGORY_SINGULAR, KIND_LABELS } from './draw.js';
import { toMermaid } from './mermaid.js';

export function toMarkdown(graph, view, opts = {}) {
  const p = graph.project;
  const link = (ev) => {
    const label = `${ev.file}:${ev.line}`;
    const url = blobUrl(p.repoUrl, p.commit, p.prefix, ev.file, ev.line);
    return url ? `[${label}](${url})` : `\`${label}\``;
  };
  const byId = new Map(view.nodes.map((n) => [n.id, n]));
  const out = new Map();
  const inc = new Map();
  for (const e of view.edges) {
    if (!out.has(e.from)) out.set(e.from, []);
    out.get(e.from).push(e);
    if (!inc.has(e.to)) inc.set(e.to, []);
    inc.get(e.to).push(e);
  }
  const s = graph.summary;
  const lines = [];
  lines.push(`# ${p.name} architecture`, '');
  const at = p.commit ? ` at commit \`${shortSha(p.commit)}\`` : '';
  lines.push(`> Generated by [Stackmap](https://github.com/AnshumaanSinghh/Stackmap) from the code${at}. Every item links to the line of code that put it on the map. Regenerate with \`npx stackmap-cli --format md\`.`, '');
  if (opts.mermaid !== false) lines.push('```mermaid', toMermaid(view), '```', '');

  lines.push('## At a glance', '');
  lines.push('| | |', '|---|---|');
  const row = (k, v) => v && lines.push(`| ${k} | ${v} |`);
  row('Apps', s.apps);
  row('Services', s.services);
  row('Workers', s.workers);
  row('Libraries', s.libraries);
  row('Data stores', s.datastores);
  row('Third-party services', s.external);
  row('Languages', s.languages.slice(0, 5).map((l) => l.name).join(', '));
  row('Deploys with', s.deploy.join(', '));
  lines.push('');

  const units = view.nodes.filter((n) => n.unit || n.container || n.custom && !['datastore', 'external'].includes(n.kind));
  if (units.length) {
    lines.push('## Apps and services', '');
    for (const n of units) {
      const kind = n.container ? 'Container' : KIND_LABELS[n.kind] ?? n.kind;
      const bits = [kind, ...(n.frameworks ?? [])].join(' · ');
      lines.push(`### ${n.name}`, '');
      lines.push(`${bits}${n.path ? ` · \`${n.path}\`` : ''}${n.description ? `  \n${n.description}` : ''}`, '');
      const talks = (out.get(n.id) ?? []).map((e) => describeEdge(e, byId.get(e.to)));
      if (talks.length) lines.push(`- **Talks to:** ${talks.join(', ')}`);
      const usedBy = (inc.get(n.id) ?? []).map((e) => byId.get(e.from)?.name).filter(Boolean);
      if (usedBy.length) lines.push(`- **Used by:** ${usedBy.join(', ')}`);
      if (n.platforms?.length) lines.push(`- **Deploys with:** ${n.platforms.join(', ')}`);
      if (n.env?.length) {
        const shown = n.env.slice(0, 24).map((x) => `\`${x}\``).join(', ');
        lines.push(`- **Reads env:** ${shown}${n.env.length > 24 ? ` and ${n.env.length - 24} more` : ''}`);
      }
      if (n.evidence?.[0]) lines.push(`- **Defined in:** ${link(n.evidence[0])}`);
      lines.push('');
    }
  }

  const techTable = (title, list) => {
    if (!list.length) return;
    lines.push(`## ${title}`, '');
    lines.push('| Name | Kind | Used by | Evidence |', '|---|---|---|---|');
    for (const n of list) {
      const usedBy = [...new Set((inc.get(n.id) ?? []).map((e) => byId.get(e.from)?.name).filter(Boolean))];
      const ev = (n.evidence ?? []).slice(0, 2).map(link).join('<br>');
      const name = n.url ? `[${n.name}](${n.url})` : n.name;
      lines.push(`| ${name} | ${CATEGORY_SINGULAR[n.category] ?? ''} | ${usedBy.join(', ') || '—'} | ${ev || '—'} |`);
    }
    lines.push('');
  };
  techTable('Data', view.nodes.filter((n) => n.column === 'data'));
  techTable('Third-party services', view.nodes.filter((n) => n.column === 'external'));

  const declared = view.edges.filter((e) => e.declaredOnly);
  if (declared.length) {
    lines.push('## Declared but never imported', '');
    lines.push('These dependencies are in a manifest, but no runtime source file imports them. They may be unused.', '');
    for (const e of declared) {
      lines.push(`- ${byId.get(e.from)?.name} → ${byId.get(e.to)?.name} (${e.evidence[0] ? link(e.evidence[0]) : ''})`);
    }
    lines.push('');
  }

  const env = new Map();
  for (const n of units) for (const name of n.env ?? []) {
    if (!env.has(name)) env.set(name, []);
    env.get(name).push(n.name);
  }
  if (env.size) {
    lines.push('## Environment variables', '');
    lines.push('| Variable | Read by |', '|---|---|');
    for (const [name, readers] of [...env].sort((a, b) => a[0].localeCompare(b[0]))) lines.push(`| \`${name}\` | ${readers.join(', ')} |`);
    lines.push('');
  }
  return lines.join('\n');
}

function describeEdge(e, target) {
  if (!target) return '';
  const via = [...(e.via ?? []).filter((v) => !v.startsWith('$')), ...(e.through ?? []).map((t) => `through ${t}`)];
  const flag = e.declaredOnly ? ' _(declared only)_' : e.confidence === 'inferred' ? ' _(inferred)_' : '';
  return `${target.name}${via.length ? ` (${via.join(', ')})` : ''}${flag}`;
}
