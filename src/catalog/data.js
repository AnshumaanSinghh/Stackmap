// Stackmap technology catalog.
//
// Every entry maps deterministic evidence (a manifest package, a Docker image, an env var name,
// an API hostname, a Terraform resource type, a URL scheme or a platform file) to one technology.
// Categories, kinds and roles are defined in ./categories.js.
//
// Conventions the matcher relies on:
// - npm / cargo / gem / composer / maven / nuget / hex: exact registry names. A trailing `*` is a
//   prefix wildcard ('@sentry/*', 'AWSSDK.*', 'com.google.cloud:*'); exact names win over wildcards,
//   and a longer wildcard should win over a shorter one.
// - pypi: PEP 503 normalised distribution names (lowercase, runs of `-_.` collapsed to `-`), so
//   'PyMySQL' is stored as 'pymysql' and 'discord.py' as 'discord-py'. Normalise requirement names
//   the same way before matching. `pyModules` lists import names only where they differ from the
//   dist name with `-` -> `_` (psycopg2-binary -> psycopg2, google-cloud-storage -> google.cloud.storage).
// - go: module path prefixes. Match on whole path segments (prefix === path or path starts with
//   prefix + '/'), so '.../service/s3' covers '.../service/s3/v2' but not '.../service/s3control';
//   the longest matching prefix wins ('github.com/aws/aws-sdk-go-v2/service/s3' beats
//   'github.com/aws/aws-sdk-go-v2').
// - docker: image repository without registry host or tag. Registry hosts (first segment containing
//   a dot or colon) are stripped, so 'docker.elastic.co/elasticsearch/elasticsearch:8' is stored as
//   'elasticsearch/elasticsearch' and 'mcr.microsoft.com/mssql/server' as 'mssql/server'.
// - env: exact names; a trailing `*` is a prefix match. Only vendor-identifying names.
// - hosts: exact host or subdomain suffix ('api.stripe.com', 'supabase.co').
// - terraform: resource type prefixes ('aws_s3_bucket' also covers 'aws_s3_bucket_policy').
// - schemes: URL schemes seen in env values, including common SQLAlchemy `dialect+driver` forms.
// - files: platform kind only; basenames or repo-relative paths.
//
// Checked against the live registries by scripts/verify-catalog.js; shape rules are in
// test/catalog.test.js.

